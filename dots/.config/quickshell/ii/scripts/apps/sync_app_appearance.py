#!/usr/bin/env python3
"""Generate apps/modules/common/Appearance.qml from the shell's Appearance.qml.

Standalone apps (qs -p apps/<app>.qml) need the shell's design tokens but none of
its side effects: the real singleton pushes Hyprland rules, gaps, borders and blur
through hyprctl, quantizes the wallpaper and imports qs.services. This copies only
the pure token blocks, verbatim, so the two never drift: rerun it whenever the
shell's Appearance changes tokens.

    python3 scripts/apps/sync_app_appearance.py          # write
    python3 scripts/apps/sync_app_appearance.py --check  # exit 1 if stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "modules/common/Appearance.qml"
DST = ROOT / "apps/modules/common/Appearance.qml"

# Token objects assigned on the root (`name: QtObject {`).
BLOCKS = ["m3colors", "colors", "rounding", "font", "animationCurves", "animation", "sizes"]
# Root properties copied as written (single line or `{ ... }` body).
PROPS = ["windowRounding", "animMultiplier", "reducedMotion"]
# Shell-only singletons the tokens touch, pinned to "no bar, desktop-first".
SUBSTITUTIONS = [
    (r"\bBarInteraction\.cornerStyle\b", "-1"),
    (r"\bBarPlacement\.vertical\b", "false"),
]

HEADER = """// GENERATED by scripts/apps/sync_app_appearance.py from modules/common/Appearance.qml.
// Do not edit: change the shell's Appearance and rerun the script.
// Tokens only. No hyprctl, no wallpaper quantizer, no qs.services.
pragma Singleton
pragma ComponentBehavior: Bound
import QtQuick
import Quickshell
import Quickshell.Io
import qs.modules.common
import qs.modules.common.functions

Singleton {
    id: root
    property QtObject m3colors
    property QtObject animation
    property QtObject animationCurves
    property QtObject colors
    property QtObject rounding
    property QtObject font
    property QtObject sizes
    property string syntaxHighlightingTheme

    // App windows are ordinary toplevels: transparency follows the manual values
    // (the shell's automatic mode needs the wallpaper quantizer, so it falls back to them).
    readonly property bool shellTransparent: Config.options?.appearance?.transparency?.enable ?? false
    property real backgroundTransparency: shellTransparent ? (Config.options?.appearance?.transparency?.backgroundTransparency ?? 0) : 0
    property real contentTransparency: shellTransparent ? (Config.options?.appearance?.transparency?.contentTransparency ?? 0) : 0

    // The shell's MaterialThemeLoader, reduced to what an app needs: apply the
    // matugen palette on start and whenever it changes (no animation, no lock palette).
    FileView {
        path: Directories.generatedMaterialThemePath
        watchChanges: true
        blockLoading: true
        onFileChanged: reload()
        onLoaded: root.applyPalette(text())
    }

    function applyPalette(content: string): void {
        let json;
        try {
            json = JSON.parse(content);
        } catch (e) {
            return; // half-written by matugen: the next change event brings the full file
        }
        for (const key in json) {
            const m3Key = "m3" + key.replace(/_([a-z])/g, g => g[1].toUpperCase());
            if (key !== "darkmode" && key !== "transparent" && root.m3colors[m3Key] !== undefined)
                root.m3colors[m3Key] = json[key];
        }
        if (typeof json.darkmode === "boolean")
            root.m3colors.darkmode = json.darkmode;
        else if (json.background ?? json.surface)
            root.m3colors.darkmode = Qt.color(json.background ?? json.surface).hslLightness < 0.5;
    }
"""


def take_block(lines, start):
    """Return the lines from `start` through the line closing its first `{`."""
    depth = 0
    opened = False
    for i in range(start, len(lines)):
        code = lines[i].split("//", 1)[0]
        depth += code.count("{") - code.count("}")
        opened = opened or "{" in code
        if opened and depth == 0:
            return lines[start:i + 1]
        if not opened:  # single-line property
            return lines[start:i + 1]
    raise SystemExit(f"unbalanced block at line {start + 1}")


def find(lines, pattern):
    rx = re.compile(pattern)
    hits = [i for i, l in enumerate(lines) if rx.match(l)]
    if len(hits) != 1:
        raise SystemExit(f"expected one match for {pattern!r}, got {len(hits)}")
    return hits[0]


def generate():
    lines = SRC.read_text().splitlines()
    out = [HEADER]
    for name in PROPS:
        i = find(lines, rf"^    (readonly )?property \w+ {name}\b")
        out.append("\n".join(take_block(lines, i)) + "\n")
    for name in BLOCKS:
        i = find(lines, rf"^    {name}: QtObject \{{")
        out.append("\n" + "\n".join(take_block(lines, i)) + "\n")
    i = find(lines, r"^    syntaxHighlightingTheme:")
    out.append("\n" + lines[i] + "\n}\n")
    text = "".join(out)
    for rx, rep in SUBSTITUTIONS:
        text = re.sub(rx, rep, text)
    leaked = sorted(set(re.findall(r"\b(Quickshell\.execDetached|HyprlandConfig|HyprlandBlur|BarInteraction|BarPlacement)\b", text)))
    if leaked:
        raise SystemExit(f"shell-only references left in the tokens: {leaked}")
    return text


def main():
    text = generate()
    if "--check" in sys.argv:
        stale = not DST.exists() or DST.read_text() != text
        print("stale" if stale else "up to date")
        sys.exit(1 if stale else 0)
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(text)
    print(f"wrote {DST.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
